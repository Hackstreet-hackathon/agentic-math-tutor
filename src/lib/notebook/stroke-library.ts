/**
 * Normalized stroke template library for handwriting recognition.
 * All coordinates are in [0,1] range (normalized to a unit bounding box).
 */

export interface SymbolDef {
  /** The raw character (for display and segmentation key) */
  char: string;
  /** LaTeX representation */
  latex: string;
  /** Width relative to height (used for layout). Default 0.6 */
  aspect: number;
  /** Each stroke is a flat [x0,y0,x1,y1,...] array, coordinates in [0,1] */
  strokes: number[][];
}

